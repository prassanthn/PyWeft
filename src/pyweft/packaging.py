"""A desktop app to hand out: ``pyweft build APP --desktop``.

PyInstaller bundles Python, the app's files and everything they use into
one runnable file: an .exe on Windows, a .app on macOS, a program on Linux.
The people who run it need nothing installed.

PyInstaller finds what to bundle by following ``import`` statements in
``.py`` files. An app's imports mostly live in ``.weft`` code blocks, which
it never reads, so this file reads them (and the app's own modules, and its
component libraries) and names every imported module for it. Component
libraries are collected whole, since their ``.weft`` files are data.

Host-only, like cli.py: never shipped to the browser.
"""

from __future__ import annotations

import ast
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

from .cli import (
    ASSETS_DIR,
    HEAD_FILE,
    CliError,
    app_assets,
    app_css_files,
    app_identity,
    app_libraries,
    app_python_files,
    app_pyweft_files,
)
from .parser import split_source

_SEP = ";" if sys.platform == "win32" else ":"  # PyInstaller's --add-data
_LAUNCHER = """\
# Generated by `pyweft build --desktop`: starts the packaged app.
import sys
from pathlib import Path

from pyweft.desktop import run_packaged

run_packaged(Path(getattr(sys, "_MEIPASS", Path(__file__).parent)) / "app")
"""


def code_imports(source: str) -> set[str]:
    """Top-level modules a piece of Python imports (``csv``, ``pyweft_ui``),
    relative imports aside. Unparseable code imports nothing here: the
    app's own error shows when it runs."""
    try:
        tree = ast.parse(source)
    except SyntaxError:
        return set()
    names: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            names.update(alias.name.split(".")[0] for alias in node.names)
        elif isinstance(node, ast.ImportFrom) and node.module and not node.level:
            names.add(node.module.split(".")[0])
    return names


def _weft_imports(path: Path) -> set[str]:
    try:
        _, code, _ = split_source(path.read_text(encoding="utf-8"))
    except Exception:  # noqa: BLE001 - a broken file fails at run time instead
        return set()
    return code_imports(code)


def app_imports(app_dir: Path) -> set[str]:
    """Every module the app's code imports, from its .weft code blocks, its
    own .py modules and its component libraries, minus its own modules
    (bundled as files, not found by PyInstaller)."""
    names: set[str] = set()
    for rel in app_pyweft_files(app_dir):
        names |= _weft_imports(app_dir / rel)
    own = set()
    for rel in app_python_files(app_dir):
        names |= code_imports((app_dir / rel).read_text(encoding="utf-8"))
        own.add(Path(rel).parts[0].removesuffix(".py"))
    for library in app_libraries(app_dir):
        for rel in library.files:
            path = library.folder / rel
            if rel.endswith(".weft"):
                names |= _weft_imports(path)
            elif rel.endswith(".py"):
                names |= code_imports(path.read_text(encoding="utf-8"))
    # Browser-only modules don't exist here; code that needs them guards.
    return names - own - {"js", "pyodide", "pyodide_js", "micropip", "__future__"}


def app_file_name(title: str) -> str:
    """The title as a file name: ``Acme Orders`` stays, ``A/B: C`` loses
    what file systems refuse."""
    name = re.sub(r'[<>:"/\\|?*\x00-\x1f]', "", title).strip(" .")
    return name or "app"


def _stage(app_dir: Path, into: Path) -> None:
    # Only what the app ships: never dist/, a .venv or anything else lying
    # around in its folder.
    files = app_pyweft_files(app_dir) + app_python_files(app_dir) + app_css_files(app_dir)
    files += [f"{ASSETS_DIR}/{rel}" for rel in app_assets(app_dir)]
    files += [name for name in ("pyproject.toml", HEAD_FILE) if (app_dir / name).is_file()]
    for rel in files:
        target = into / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(app_dir / rel, target)


def _icon_args(app_dir: Path, icon: str | None) -> list[str]:
    # PyInstaller wants an .ico on Windows and an .icns on macOS; Linux
    # programs carry no icon of their own.
    if icon is None:
        return []
    wanted = {"win32": ".ico", "darwin": ".icns"}.get(sys.platform)
    if wanted and icon.lower().endswith(wanted):
        return ["--icon", str((app_dir / icon).resolve())]
    if wanted:
        print(f"pyweft: the built app keeps the default icon: {icon} isn't an {wanted} file")
    return []


def pyinstaller_args(app_dir: Path, out: Path, work: Path) -> list[str]:
    """The PyInstaller command line for an app, staged in ``work``."""
    app_dir = Path(app_dir).resolve()
    identity = app_identity(app_dir)
    staged = work / "app"
    launcher = work / "launch.py"
    args = [
        str(launcher),
        "--onefile",
        "--windowed",  # no console window behind the app
        "--noconfirm",
        "--log-level", "WARN",
        "--name", app_file_name(identity.title),
        "--distpath", str(Path(out).resolve()),
        "--workpath", str(work / "build"),
        "--specpath", str(work),
        "--add-data", f"{staged}{_SEP}app",
        "--collect-all", "pyweft",  # the runtime, the page, every module
    ]
    for library in app_libraries(app_dir):
        args += ["--collect-all", library.name]
    for name in sorted(app_imports(app_dir)):
        args += ["--hidden-import", name]
    return args + _icon_args(app_dir, identity.icon)


def build_desktop(app_dir: Path, out: Path) -> Path:
    """Build the app into ``out`` and return what was built."""
    app_dir = Path(app_dir).resolve()
    app_pyweft_files(app_dir)  # fails fast without an app.weft
    identity = app_identity(app_dir)  # and on a mistake in the settings
    from .desktop import window_options

    window_options(app_dir)
    try:
        import PyInstaller  # noqa: F401
        import webview  # noqa: F401
    except ImportError:
        raise CliError(
            "building a desktop app needs PyInstaller and pywebview: "
            'uv add --dev "pyweft[package]"  (or: pip install "pyweft[package]")'
        ) from None

    with tempfile.TemporaryDirectory(prefix="pyweft-build-") as tmp:
        work = Path(tmp)
        _stage(app_dir, work / "app")
        (work / "launch.py").write_text(_LAUNCHER, encoding="utf-8")
        args = pyinstaller_args(app_dir, out, work)
        print(f"pyweft: building {identity.title} with PyInstaller (this takes a minute)")
        result = subprocess.run([sys.executable, "-m", "PyInstaller", *args], cwd=work)
        if result.returncode != 0:
            raise CliError("PyInstaller failed; its messages are above")

    name = app_file_name(identity.title)
    built = Path(out) / {"win32": f"{name}.exe", "darwin": f"{name}.app"}.get(sys.platform, name)
    print(f"built {built}")
    return built
